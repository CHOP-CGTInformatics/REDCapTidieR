#' @title Convert Mixed Structure Instruments to Repeating Instruments
#'
#' @description
#' For longitudinal projects where users set `allow_mixed_structure` to `TRUE`,
#' this function will handle the process of setting the nonrepeating parts of the
#' instrument to repeating ones with a single instance.
#'
#' @param db_data_long The longitudinal REDCap database output defined by
#' \code{REDCapR::redcap_read_oneshot()$data}
#' @param mixed_structure_ref Reference dataframe containing mixed structure
#' fields and forms.
#'
#' @return
#' The export with repeat instrument and instance values populated for mixed rows.
#'
#' @keywords internal

convert_mixed_instrument <- function(db_data_long, mixed_structure_ref) {
  for (i in seq_len(nrow(mixed_structure_ref))) {
    field <- mixed_structure_ref$field_name[i]
    form <- mixed_structure_ref$form_name[i]

    # Create an update mask column to identify which mixed structure rows need updates
    db_data_long <- mutate(
      db_data_long,
      update_mask = case_when(
        # repeat separately instances
        !is.na(!!as.symbol(field)) &
          is.na(.data$redcap_repeat_instance) ~ TRUE,
        # repeat together instances
        !is.na(!!as.symbol(field)) &
          !is.na(.data$redcap_repeat_instance) &
          is.na(.data$redcap_repeat_instrument) ~ TRUE,
        TRUE ~ FALSE
      )
    )

    repeat_together_present <- any(
      is.na(db_data_long$redcap_repeat_instrument) &
        !is.na(db_data_long$redcap_repeat_instance)
    )

    if (!"redcap_event_instance" %in% names(db_data_long) && repeat_together_present) {
      db_data_long <- mutate(db_data_long, redcap_event_instance = NA)
      db_data_long <- relocate(db_data_long, "redcap_event_instance", .after = "redcap_repeat_instance")
    }

    if (repeat_together_present) {
      db_data_long <- mutate(
        db_data_long,
        redcap_event_instance = case_when(
          # Shift form instances to event instances for repeat-together types
          update_mask & is.na(redcap_repeat_instrument) ~ redcap_repeat_instance,
          TRUE ~ redcap_event_instance
        )
      )
    }

    # Assign update data based on rules below
    db_data_long <- mutate(
      db_data_long,
      redcap_repeat_instance = case_when(
        # Assign an instance to nonrepeating rows in events that repeat separately
        update_mask & is.na(redcap_repeat_instance) ~ 1,
        # The original instance has been moved to redcap_event_instance
        update_mask & is.na(redcap_repeat_instrument) ~ NA,
        TRUE ~ .data$redcap_repeat_instance
      ),
      redcap_repeat_instrument = case_when(
        update_mask ~ form,
        TRUE ~ .data$redcap_repeat_instrument
      )
    )
    db_data_long <- select(db_data_long, -"update_mask")
  }

  db_data_long
}

#' @title Get Mixed Structure Instrument List
#'
#' @description
#' Define fields in a given project that are used in both a repeating and
#' nonrepeating manner.
#'
#' @param db_data The REDCap database output generated by
#' \code{REDCapR::redcap_read_oneshot()$data}
#'
#' @returns a dataframe
#'
#' @keywords internal

get_mixed_structure_fields <- function(db_data) {
  # Identify columns to check for repeat/nonrepeat behavior
  safe_cols <- c(
    names(db_data)[1],
    "redcap_event_name",
    "redcap_repeat_instrument",
    "redcap_repeat_instance",
    "redcap_data_access_group"
  )

  check_cols <- setdiff(names(db_data), safe_cols)

  if (length(check_cols) == 0L) {
    return(data.frame())
  }

  is_repeating <- !is.na(db_data["redcap_repeat_instrument"])
  rep_and_nonrep <- map_lgl(check_cols, function(field) {
    populated <- !is.na(db_data[field])
    any(populated & is_repeating) && any(populated & !is_repeating)
  })

  out <- data.frame(field_name = check_cols, rep_and_nonrep = rep_and_nonrep)
  if (is.factor(out$field_name)) {
    # Older R versions create factor levels in field order when rows are bound.
    out$field_name <- factor(out$field_name, levels = check_cols)
  }
  out
}

#' @title Index mixed structure fields by instrument
#' @description Match populated mixed fields to the instruments in project metadata.
#' @param db_data A longitudinal REDCap export.
#' @param db_metadata Metadata for the export.
#' @returns A list of mixed structure reference data frames keyed by instrument.
#' @noRd
get_mixed_fields_by_form <- function(db_data, db_metadata) {
  fields <- get_mixed_structure_fields(db_data)
  fields <- filter(fields, .data$rep_and_nonrep & !str_ends(.data$field_name, "_form_complete"))
  fields <- left_join(fields, select(db_metadata, "field_name", "form_name"), by = "field_name")
  split(fields, fields$form_name)
}
